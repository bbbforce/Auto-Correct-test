import os
from autogen_agentchat.agents import AssistantAgent
from autogen_ext.models.openai import OpenAIChatCompletionClient
from autogen_agentchat.messages import MultiModalMessage
from autogen_core import Image
from utils import setup_logger
from models import EvaluationResult
from llm_utils import parse_llm_response


class ResultEvaluationAgent:
    def __init__(self, api_key: str, model: str = "gpt-4o", base_url: str = None, log_dir: str = None):
        self.logger = setup_logger('result_evaluation_agent', 'result_evaluation_agent.log', log_dir=log_dir)
        # We need a model with vision capabilities. gpt-4o supports it.
        self.model_client = OpenAIChatCompletionClient(
            model=model, 
            api_key=api_key, 
            base_url=base_url,
            model_info={'vision': True, 'function_calling': True, 'json_output': True, 'family': 'unknown'},
            temperature=0
        )
        
        # 注意：评估 Agent 只负责诊断，不负责修复代码（责任链清晰化）
        system_message = """
You are a senior Mechanical and Physical Simulation Expert. Your task is to evaluate the logical and physical correctness of FEniCS simulation results based on text metrics and generated visualization plots.

🚨 Critical Physical Heuristics to check:
1. **Displacement/Deformation**: 
   - Is the magnitude order structurally reasonable? (e.g., A 1m steel beam shouldn't deflect by 10m unless it's a specific large-deformation nonlinear problem).
   - Are fixed boundary conditions visually enforced? (Displacement at fixed supports MUST be exactly 0, indicated by the colorbar).
2. **Stress Distribution (Von Mises, etc.)**: 
   - Does stress concentrate where expected? (e.g., sharp corners, roots of cantilevers, points of applied point loads).
   - Is there expected symmetry if geometry and loads are symmetric?
3. **Temperature/Heat Flow**:
   - Does heat flow from hot to cold?
   - Do the maximum/minimum temperatures exceed the applied boundary temperatures without internal heat sources? (Violation of Maximum Principle).
4. **General Plot Quality**:
   - Is there a clear title and colorbar?

📦 Input:
- Original Prompt: What the user actually wanted.
- Executed Code: The code that ran successfully.
- Text Output: The stdout logs which should contain max/min values.
- Result Image: The plot generated by FEniCS.

📦 Output Format (JSON only!):
{
  "is_correct": true or false,
  "confidence": 0.0 to 1.0,
  "feedback": "Detailed explanation. If false, precisely describe what physical heuristic failed (e.g., 'The plot shows max displacement at the fixed end, which violates the boundary condition.')"
}

⚠️ IMPORTANT: You are ONLY responsible for EVALUATION. Do NOT attempt to fix the code. Only return is_correct, confidence, and feedback.
"""
        self.agent = AssistantAgent(
            name="result_evaluation_agent",
            model_client=self.model_client,
            system_message=system_message
        )

    async def evaluate_results(self, prompt: str, code: str, simulation_output: str, image_paths: list[str]) -> EvaluationResult:
        self.logger.info("Evaluating simulation results...")
        
        # Step 1: 将所有文本拼接为单一字符串
        text_content = (
            f"--- Original USER Prompt ---\n{prompt}\n\n"
            f"--- Executed FEniCS Code ---\n{code}\n\n"
            f"--- Terminal Output & Metrics ---\n{simulation_output}\n\n"
            f"--- Result Images ---\n"
        )

        # Step 2: 收集有效的 autogen_core.Image 对象
        images = []
        for img_path in image_paths:
            if os.path.exists(img_path):
                try:
                    ag_image = Image.from_file(img_path)
                    images.append(ag_image)
                    self.logger.info(f"Loaded image {img_path} for vision evaluation.")
                except Exception as e:
                    self.logger.error(f"Failed to load image {img_path}: {e}")
                    text_content += f"[Failed to load image {img_path}: {e}]\n"
            else:
                text_content += f"[Image file not found: {img_path}]\n"
                self.logger.warning(f"Image not found: {img_path}")

        if not image_paths:
            text_content += "[No plots/images were generated by the simulation]\n"

        try:
            # Step 3: 正确构造 task 传给 agent.run()
            if images:
                mm_content = [text_content] + images
                task = MultiModalMessage(content=mm_content, source="user")
            else:
                task = text_content

            result = await self.agent.run(task=task)
            response_text = result.messages[-1].content
            
            # 处理 response_text 可能是列表（MultiModal 回复）的情况
            if isinstance(response_text, list):
                response_text = "".join(
                    part if isinstance(part, str) else "" for part in response_text
                )
            response_text = response_text.strip()

            evaluation = parse_llm_response(response_text, EvaluationResult)
            return evaluation
            
        except Exception as e:
            self.logger.error(f"Evaluation failed: {e}")
            return EvaluationResult(
                is_correct=False,
                confidence=0.0,
                feedback=f"Evaluation agent error: {str(e)}",
            )
